let currentLang = "en";
const toggle = document.getElementById("langToggle");

function applyLanguage(lang){
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if(translations[lang][key]) el.textContent = translations[lang][key];
  });
  toggle.textContent = lang === "en" ? "FR" : "EN";
  currentLang = lang;
}

toggle.addEventListener("click", () => applyLanguage(currentLang === "en" ? "fr" : "en"));

const menuBtn = document.querySelector(".menu-btn");
const nav = document.getElementById("mainNav");
menuBtn.addEventListener("click", () => {
  const isOpen = nav.classList.toggle("open");
  menuBtn.setAttribute("aria-expanded", String(isOpen));
});
nav.querySelectorAll("a").forEach(a => a.addEventListener("click", () => {
  nav.classList.remove("open");
  menuBtn.setAttribute("aria-expanded", "false");
}));

document.getElementById("quoteForm").addEventListener("submit", function(e){
  e.preventDefault();
  const name = document.getElementById("name").value.trim();
  const company = document.getElementById("company").value.trim();
  const email = document.getElementById("email").value.trim();
  const phone = document.getElementById("phone").value.trim();
  const message = document.getElementById("message").value.trim();

  const subject = encodeURIComponent("Quote Request - J Reyes Nettoyage");
  const body = encodeURIComponent(
    `Name: ${name}\nCompany: ${company}\nEmail: ${email}\nPhone: ${phone}\n\nCleaning request:\n${message}`
  );
  window.location.href = `mailto:jreyesnettoyage@gmail.com?subject=${subject}&body=${body}`;
});

